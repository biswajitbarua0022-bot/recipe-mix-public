import { expect, test } from '@playwright/test'

test('opens the production Recipe Box, filters it and reaches each screen', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('response', (response) => {
    if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`)
  })

  await page.setViewportSize({ width: 1440, height: 1016 })
  await page.goto('./')
  await expect(page).toHaveURL(/\/recipe-mix-public\/#\/recipes$/)
  await expect(page.getByRole('heading', { name: 'Recipe Box' })).toBeVisible()
  const recipes = page.getByRole('list', { name: 'Recipes' })
  await expect(recipes.getByRole('listitem')).toHaveCount(10)

  const search = page.getByRole('searchbox', { name: 'Search recipes or ingredients' })
  await search.fill('curry leaves')
  await expect(recipes.getByRole('listitem')).toHaveCount(3)
  await expect(recipes.getByRole('link', { name: 'Poha' })).toBeVisible()
  await search.fill('biryani')
  await expect(page.getByRole('heading', { name: 'No recipes match “biryani”' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()

  await page.getByRole('button', { name: 'Favourites', exact: true }).click()
  await expect(recipes.getByRole('listitem')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear all', exact: true }).click()
  await expect(recipes.getByRole('listitem')).toHaveCount(10)
  await page.getByRole('complementary', { name: 'Filters' }).getByRole('button', { name: 'Non-veg' }).click()
  await expect(recipes.getByRole('listitem')).toHaveCount(2)
  await expect(recipes.getByRole('link', { name: 'Chicken Curry' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove Non-veg filter' }).click()

  await page.getByRole('link', { name: 'Add recipe' }).click()
  await expect(page.getByRole('heading', { name: 'Add recipe' })).toBeVisible()
  await expect(page.getByLabel('Recipe title')).toBeVisible()
  await page.getByRole('button', { name: 'Cancel' }).click()

  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await nav.getByRole('link', { name: 'Recipe Box' }).click()
  await recipes.getByRole('link', { name: 'Dal Tadka' }).click()
  await expect(page.getByRole('heading', { name: 'Dal Tadka' })).toBeVisible()
  await page.getByLabel('Recipe actions').click()
  await page.getByRole('link', { name: 'Edit recipe' }).click()
  await expect(page.getByRole('heading', { name: 'Edit recipe' })).toBeVisible()
  await expect(page.getByLabel('Recipe title')).toHaveValue('Dal Tadka')
  await page.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('link', { name: 'Start cooking' }).click()
  await expect(page.getByRole('region', { name: 'Cook Mode' })).toBeVisible()
  await page.getByRole('link', { name: 'Exit' }).click()
  await page.getByRole('link', { name: 'Recipe Box' }).click()

  await nav.getByRole('link', { name: 'Cookbooks' }).click()
  await expect(page.getByRole('heading', { name: 'No cookbooks yet' })).toBeVisible()
  await nav.getByRole('link', { name: 'Planner' }).click()
  await page.reload()
  await expect(page).toHaveURL(/\/recipe-mix-public\/#\/planner$/)
  await expect(page.getByRole('heading', { name: 'Planner' })).toBeVisible()
  await nav.getByRole('link', { name: 'Groceries' }).click()
  await expect(page.getByRole('heading', { name: 'Groceries' })).toBeVisible()
  await page.getByRole('link', { name: 'Settings' }).click()
  await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible()
  expect(errors).toEqual([])
})

test('uses bottom navigation and an accessible filter sheet on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./#/recipes')

  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(nav).toHaveCSS('position', 'fixed')
  await expect(nav.getByRole('link', { name: 'Recipe Box' })).toHaveAttribute('aria-current', 'page')
  const filters = page.getByRole('button', { name: 'Filters', exact: true })
  await filters.click()
  const sheet = page.getByRole('dialog', { name: 'Filters' })
  await expect(sheet).toBeVisible()
  await sheet.getByRole('button', { name: 'North Indian' }).click()
  await sheet.getByRole('button', { name: 'Show 6 recipes' }).click()
  await expect(sheet).toBeHidden()
  await expect(page.getByRole('status')).toHaveText('Showing 6 of 10 recipes')
  await expect(page.getByRole('button', { name: /^Filters/ })).toBeFocused()
  await expect(page.getByRole('button', { name: 'Remove North Indian filter' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove North Indian filter' }).click()
  await expect(page.getByRole('status')).toHaveText('Showing 10 of 10 recipes')
  await filters.click()
  await page.keyboard.press('Escape')
  await expect(sheet).toBeHidden()
  await expect(filters).toBeFocused()
  expect(await page.locator('body').evaluate((element) => element.scrollWidth)).toBe(390)
})
