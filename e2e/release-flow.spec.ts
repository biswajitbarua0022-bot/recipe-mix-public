import { expect, test } from '@playwright/test'

test('takes a newly saved recipe through planning, shopping and cooking', async ({ page }) => {
  test.setTimeout(60_000)
  await page.clock.setFixedTime(new Date('2026-01-05T12:00:00Z'))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('./#/recipes/new')
  await page.getByLabel('Recipe title').fill('Lemon Cumin Rice')
  await page.getByLabel('Servings', { exact: true }).fill('2')
  await page.getByLabel('Prep time').fill('5')
  await page.getByLabel('Cook time').fill('15')
  const ingredient = page.getByRole('group', { name: 'Ingredient 1' })
  await ingredient.getByLabel('Ingredient', { exact: true }).fill('Basmati rice')
  await ingredient.getByLabel('Amount').fill('½')
  await ingredient.getByLabel('Unit').selectOption('cup')
  await ingredient.getByLabel('Aisle').selectOption('Dals, rice & grains')
  await page.getByLabel('Step 1', { exact: true }).fill('Simmer the rice, then add lemon and toasted cumin.')
  await page.getByRole('button', { name: 'Save recipe' }).first().click()
  await expect(page.getByRole('heading', { name: 'Lemon Cumin Rice' })).toBeVisible()
  await page.getByRole('button', { name: 'More servings' }).click()
  await page.getByRole('button', { name: 'More servings' }).click()
  await page.getByRole('button', { name: 'Add to plan' }).click()
  const schedule = page.getByRole('dialog', { name: 'Add Lemon Cumin Rice to the plan' })
  await expect(schedule.getByRole('spinbutton', { name: 'Servings' })).toHaveValue('4')
  await schedule.getByRole('button', { name: 'Dinner Free' }).click()
  await schedule.getByRole('button', { name: 'Add to Mon dinner' }).click()

  await page.goto('./#/planner')
  await page.reload()
  await expect(page).toHaveURL(/\/recipe-mix-public\/#\/planner$/)
  const plannedMeal = page.getByRole('button', { name: /Lemon Cumin Rice.*Serves 4/, description: /Monday 5 Jan dinner/ })
  await expect(plannedMeal).toBeVisible()
  await page.getByRole('button', { name: 'Generate grocery list' }).click()
  const rice = page.getByRole('checkbox', { name: 'Basmati rice, 1 cup', exact: true })
  await rice.click()
  await page.reload()
  await expect(rice).toBeChecked()

  await page.goto('./#/planner')
  await plannedMeal.click()
  const meal = page.getByRole('dialog', { name: 'Lemon Cumin Rice' })
  await meal.getByRole('link', { name: 'View recipe' }).click()
  await page.getByRole('link', { name: 'Start cooking' }).click()
  await expect(page.getByLabel('Current instruction')).toContainText('Simmer the rice')
  await page.getByRole('button', { name: 'Ingredients · 4 servings', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Ingredients · 4 servings' })).toContainText('1 cup')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Finish cooking' }).click()
  await expect(page.getByRole('heading', { name: 'Lemon Cumin Rice is ready' })).toBeFocused()
})
